"""P6's per-tick IK: `ik = "arm_qp"`, and the QP every other solver builds on.
Design: `docs/infra_logic/ik_solvers.md`, "`arm_qp` — the per-tick QP".

A thin wrapper over `elrobot_deploy.robot.mujoco_model`'s `DualArmIK`, which is a mink differential
QP with two `FrameTask`s, a `PostureTask`, and `ConfigurationLimit` +
`VelocityLimit` + `CollisionAvoidanceLimit`. The stack is unchanged in
structure; what this file adds is the four properties the deploy loop needs and
the QP by itself does not have:

  * **an explicit seed on every solve.** The seed sets *both* the QP
    configuration and the posture target. Setting only the configuration would
    leave the smoothness cost pulling toward whatever posture was last written,
    and P6 re-solves ticks it has already solved from a *different* predecessor
    every time a new chunk lands — a warm start alone is not
    well-defined under that.

  * **early exit.** One QP iterate at a time, stopping as soon as the worst
    flange position error is inside `ik_early_stop`, rather than always paying
    `max_iters`. Roughly 3.7 iterations in practice.

  * **the waist pinned at whatever angle the caller passes.** `kinematics.place()`
    writes it into `qpos` before the arm seed, and the model's existing 1e-9
    rad/s velocity limit on every non-arm joint holds it there through the
    solve. Zeroing the whole `qpos` instead would solve the arms as
    though the trunk were always upright, which is also the wrong collision
    geometry. Using `place()` rather than an equivalent local copy is the point:
    it is the *same* function P1's FK calls, so the pose the policy observes and
    the pose the IK solves for cannot come to be expressed against different
    trunk configurations.

    **This argument is the trunk the arm will actually hang off, which is the
    MEASURED one — see `p6_target`.** Not the commanded one: on the reference
    robot those differ permanently — the trunk rests against a physical
    obstruction 0.039 rad (2.25 deg) forward of the zero it is commanded to,
    and no torque moves it (measured). Solving against
    the commanded trunk asks the QP the wrong question. It answers it correctly,
    the arm reaches the pose it was told to in a frame the robot is not in, and
    every flange lands 8-11 mm out with nothing reporting it.

  * **a wall-clock budget.** The requirement is "no valid solution within
    `dt`", not "no solution within N iterations": an iterate that takes 10 ms
    under load must not be allowed to run 20 of itself. `ik_max_iters` stays as
    a secondary cap.

**`ok=False` means one thing only: the wall clock ran out.** If no valid
solution is found in `1/control_hz` seconds, the iteration is ended — and it
is deliberately not a quality gate.

The reason is measured. This QP has a hard error floor set by the `PostureTask`
trading flange position against staying near the seed: on targets that are
*exactly* reachable (generated by FK from a real posture) the worst position
error settles at 7e-5 m for a 0.02 rad per-tick step but 1.3e-3 m for a 0.3 rad
step, and 200 further iterates do not improve it. Gating `ok` on
`err <= ik_early_stop` therefore refuses every realistic tick and the robot
never moves at all.

So `ik_early_stop` is what its name says — stop iterating, this is good enough —
and hitting `ik_max_iters`, or a QP that stops moving because it cannot do
better, both return the configuration reached with `ok=True`. An unreachable
target is then an arm that goes as far as it can, with the residual reported in
`tracking_error`, rather than a silently dropped tick.

Only the *position* error gates the early exit: at
these costs (position 1.0, orientation 0.3) the orientation residual is the one
the QP trades away deliberately, and gating on it would spend the whole budget
re-litigating that trade every tick.
"""

from __future__ import annotations

import numpy as np

from elrobot_deploy.robot import kinematics as kin
from elrobot_deploy.runtime.shared_memory import schema
from elrobot_deploy.runtime.timing import now
from elrobot_deploy.robot.kinematics import SIDES


class DualArmSolver:
    """Base-frame flange poses + a commanded waist -> 14 arm joints.

    Everything mujoco/mink is imported in `__init__`, never at module scope, so
    that importing `elrobot_deploy` costs nothing in the processes that must not
    touch this stack at all (P7).
    """

    def __init__(self, cfg, *, backend=None, urdf: str | None = None,
                 max_iters: int | None = None, rel: float | None = None,
                 abs_tol: float = 2e-6, min_iters: int = 2, tcp=None):
        """`max_iters` overrides `cfg.ik_max_iters` for this instance; `rel` turns
        on the convergence stop (below). Both default to the deployed behaviour.

        `tcp`: the robot file's `(7,)` `[end_effector] tcp`, or None. **With
        one, the QP drives the TCP**: each flange target is composed with the
        offset into a TCP target, the task frame is the model's TCP site, and
        the returned error and the early stop are at the TCP. Without, all of
        it is at the flange. A perfect solve is the same joint angles either
        way; what differs is how a miss is traded between position and
        orientation — at the fingertips or at the wrist."""
        import mujoco

        from elrobot_deploy.robot import mujoco_model as _g1
        from elrobot_deploy.robot import g1d_model as _g1d

        self._mujoco = mujoco
        self.cfg = cfg
        self.dt = float(cfg.dt)
        self.early_stop = float(cfg.ik_early_stop)
        self.max_iters = int(cfg.ik_max_iters if max_iters is None else max_iters)
        #: **Convergence stop** (off by default): quit when an
        #: iterate improves the worst flange error by less than `rel` of itself
        #: (or `abs_tol` metres), after `min_iters`. Measured on one recorded
        #: rollout (cProfile, plain arm): one iterate is ~0.38 ms and 73% of ticks ran
        #: the full 20 because the posture term's floor keeps the flange just
        #: outside the 0.1 mm early stop — most of every tick re-solving a
        #: configuration that had stopped improving. The planners run three
        #: solves per tick and buy their budget here.
        self.rel, self.abs_tol, self.min_iters = rel, float(abs_tol), int(min_iters)

        # The same model P1's FK loads (the robot file's `[model] urdf`). Two
        # different models here would put the observed flange and the solved
        # flange in different geometries — a silent bias, not a failure.
        self.tcp = None if tcp is None else np.asarray(tcp, np.float64).reshape(7)
        if backend is None:
            backend = _g1d.G1DBackend(urdf, tcp=self.tcp)
        elif (self.tcp is None) != (getattr(backend, "tcp", None) is None):
            raise ValueError("the backend's TCP site does not match this "
                             "solver's tcp: build it with G1DBackend(tcp=...)")
        self.backend = backend
        #: flange -> TCP as a 4x4, or None.
        self._X = None if self.tcp is None else kin.pose_to_mat(self.tcp)
        # Both collision sets are the G1-D's. The trunk is a wheeled base, a lift
        # column and the two waist links, where the humanoid's default would name
        # a pelvis and six hip links that do not exist here; the arm set adds the
        # Dex-1's jaws, which no other model has. Passing the wrong one is now an
        # error rather than a quietly empty group — see `collision_geom_groups`.
        self.ik = _g1.DualArmIK(self.backend,
                                posture_cost=cfg.ik_posture_cost,
                                collision_min_dist=cfg.ik_collision_min_dist,
                                trunk_bodies=_g1d.TRUNK_COLLISION_BODIES,
                                arm_bodies=_g1d.ARM_COLLISION_BODIES)
        self._jmap = kin.joint_addresses(self.backend)

        # mink solves in the model's world frame; the contract is the base frame.
        # The base is fixed, so this is constant — computing it per tick would
        # also make it a function of whatever qpos the last solve left behind.
        self.base = self.backend.base_pose()

    # --- the surface `ik_solvers` composes on ------------------------------
    #
    # The planners there wrap this solver rather than subclass it: a pull toward
    # a planned posture is one more task in the QP, a motion cap one more limit,
    # and the seed placement is the same three writes in the same order. These
    # are the hooks; the underscored names below them are kept for the IK
    # bench, which grew on them.

    @property
    def jmap(self):
        return self._jmap

    def targets_world(self, pose_2x7) -> list[np.ndarray]:
        """Base-frame FLANGE poses -> world-frame 4x4 targets of the DRIVEN
        frame, left then right: the flange targets composed with the TCP
        offset when the solver has one, else the flange targets themselves."""
        out = [self.base @ kin.pose_to_mat(np.asarray(pose_2x7[h], dtype=np.float64))
               for h in range(schema.N_HANDS)]
        return out if self._X is None else [T @ self._X for T in out]

    def position_error(self, targets) -> float:
        """Worst position error of the DRIVEN frame (the TCP when there is one,
        else the flange), metres, at the backend's current qpos.

        Read off the model, which `set_qpos`/`mj_forward` has just refreshed —
        the QP's own residual is a velocity, not a distance, and reports
        nothing about a target the constraints will never let it reach.
        """
        return max(float(np.linalg.norm(self.backend.ik_xpos(s) - T[:3, 3]))
                   for s, T in zip(SIDES, targets))

    def place(self, seed_q14, waist_3) -> None:
        """Seed: model placement (waist pinned at the given angles), the QP
        configuration, and the posture target — all three from the same q, in
        that order, because `config.update()` must see the placed qpos."""
        kin.place(self.backend, seed_q14, waist_3, self._jmap)
        self._mujoco.mj_forward(self.backend.model, self.backend.data)
        self.ik.config.update(self.backend.data.qpos.copy())
        self.ik.posture.set_target_from_configuration(self.ik.config)

    def add_task(self, task) -> None:
        """One more mink task in the QP, after the flange and posture tasks."""
        self.ik._task_list = [*self.ik._task_list, task]

    def add_limit(self, limit) -> None:
        """One more mink limit in the QP."""
        self.ik._limits.append(limit)

    def arm_q(self) -> np.ndarray:
        """The (14,) arm configuration the QP currently holds."""
        return self.ik.config.q[self._jmap.arm].copy()

    _targets_world = targets_world
    _position_error = position_error
    _arm = arm_q

    # --- the solve ----------------------------------------------------------

    def solve(self, pose_2x7, waist_3, seed_q14, budget: float | None = None):
        """-> `(q_arm14, tracking_error, ok)`.

        `budget` is wall clock, defaulting to one action tick. `tracking_error`
        is metres at the driven point — the TCP when the solver has one, else
        the flange — and so is the early stop. It is returned even when `ok` is
        False: it is the honest measure of how far
        the abandoned solve got, and the only thing that distinguishes "the arm
        cannot go there" from "the machine was too busy this tick".
        """
        budget = self.dt if budget is None else float(budget)
        targets = self.targets_world(pose_2x7)
        self.place(seed_q14, waist_3)

        expires = now() + budget
        err = self.position_error(targets)
        iters = 0
        while err > self.early_stop:
            if now() >= expires:
                # The one failure. P6 writes nothing and the tick becomes a hole
                # every other process already tolerates.
                return self.arm_q(), err, False
            if iters >= self.max_iters:
                break                       # secondary cap: publish what we have
            q_prev = self.ik.config.q.copy()
            self.ik.solve_tick(targets[0], targets[1], iters=1, dt=self.dt)
            iters += 1
            if np.array_equal(self.ik.config.q, q_prev):
                # `solve_tick` swallows `NoSolutionFound` and leaves the
                # configuration untouched. An iterate that moved nothing will
                # move nothing next time either — the QP is at its floor, or
                # infeasible here — so spending the rest of the budget to reach
                # the same configuration is pure latency.
                break
            new = self.position_error(targets)
            if (self.rel is not None and iters >= self.min_iters
                    and err - new < max(self.rel * err, self.abs_tol)):
                err = new
                break                       # the convergence stop (see __init__)
            err = new
        return self.arm_q(), err, True


def arm_qp(cfg, *, urdf=None, qdot_max=None, tcp=None):
    """The `arm_qp` factory (`runtime/ik/__init__.py::SOLVERS`): one QP tick per loop iteration, the
    trunk read and never commanded. `qdot_max` is P6's clamp, applied after the
    solve. `tcp` (the robot file's, or None) is the point the QP drives and its
    error is measured at; None = the flange."""
    return DualArmSolver(cfg, urdf=urdf, tcp=tcp)


arm_qp.mode = "arm"


__all__ = ["DualArmSolver", "arm_qp"]
